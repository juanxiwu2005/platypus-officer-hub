import { expect, test } from "@playwright/test"
import { closeRail, noOverflow, viewAs } from "../../../e2e/helpers"

test.beforeEach(async ({ page }) => { await page.route("**/api/health", r => r.fulfill({ json: { ok: true, configured: true, provider: "mock", model: "mock" } })) })

const details = (page: import("@playwright/test").Page) => page.locator(".detail-scroll")

test("contacts: search, filter, owner, next step and last contact in one table", async ({ page }) => {
  await page.goto("/#/partners")
  const table = page.getByTestId("contacts")
  await expect(table).toContainText("Jamie Ortiz")
  await expect(table).toContainText("Treasurer")
  await expect(table).toContainText("Due Oct 27") // next step from the timeline
  await page.getByLabel("Search partners").fill("riley")
  await expect(table.getByRole("row")).toHaveCount(2) // header + Riley
  await page.getByLabel("Search partners").fill("sponsor-prospect") // tags are searchable
  await expect(table).toContainText("Morgan Hale")
  await page.getByLabel("Search partners").fill("")
  await page.getByRole("button", { name: "Overdue", exact: true }).click()
  await expect(table).toContainText("Riley Brooks")
  await expect(table).not.toContainText("Jamie Ortiz")
  await page.getByRole("button", { name: "Mine", exact: true }).click()
  await expect(table).not.toContainText("Jamie Ortiz") // owned by the Treasurer, not Alex
  expect(await noOverflow(page)).toBeLessThanOrEqual(1)
})

test("add a contact, log an interaction, and see it in the timeline and last contact", async ({ page }) => {
  await page.goto("/#/partners")
  await page.getByRole("button", { name: "+ Add contact" }).click()
  await page.getByLabel("Partner name").fill("Mesa Print Shop (fictional)")
  await page.getByLabel("Organization", { exact: true }).fill("Mesa Print Co (fictional)")
  await page.getByRole("button", { name: "Add", exact: true }).click()
  const table = page.getByTestId("contacts")
  await expect(table).toContainText("Mesa Print Shop (fictional)")
  await expect(table).toContainText("Mesa Print Co (fictional)")
  await table.getByRole("button", { name: /Mesa Print Shop/ }).click()
  const panel = details(page)
  await expect(panel.getByRole("heading", { name: "Mesa Print Shop (fictional)" })).toBeVisible()
  await expect(panel).toContainText("Nothing logged yet")
  await panel.getByRole("button", { name: "Log interaction" }).first().click()
  const form = panel.getByRole("form", { name: "Log interaction" })
  await form.getByLabel("What happened").fill("Asked for a poster quote")
  await form.getByLabel("Outcome").fill("Quote by Friday")
  await form.getByLabel("Next step").fill("Compare quotes")
  await form.getByRole("button", { name: "Save entry" }).click()
  const timeline = panel.getByRole("list", { name: "Timeline" })
  await expect(timeline).toContainText("Asked for a poster quote")
  await expect(timeline).toContainText("Alex Rivera")
  await expect(panel).toContainText("0 days ago")
  await timeline.getByRole("checkbox").check()
  await page.reload()
  await expect(page.getByTestId("contacts")).toContainText("0d ago")
})

test("board: move a contact between stages; profile edits save when you leave the field", async ({ page }) => {
  await page.goto("/#/partners")
  await page.getByRole("button", { name: "Board", exact: true }).click()
  const board = page.getByTestId("crm-board")
  await expect(board.getByRole("region", { name: /Cold/ })).toContainText("Morgan Hale")
  await board.getByLabel("Move Morgan Hale (fictional) to stage").selectOption("warm")
  await expect(board.getByRole("region", { name: /Warm/ })).toContainText("Morgan Hale")
  await board.getByRole("button", { name: /Riley Brooks/ }).click()
  const panel = details(page)
  await panel.getByText("Profile", { exact: true }).click()
  await panel.getByLabel("Title", { exact: true }).fill("CEO")
  await panel.getByLabel("Tags (comma separated)").fill("speaker, AI")
  await panel.getByLabel("Email", { exact: true }).click() // blur saves
  await page.reload()
  await page.getByRole("button", { name: "Board", exact: true }).click()
  await expect(page.getByTestId("crm-board").getByRole("region", { name: /Warm/ })).toContainText("Morgan Hale")
  await page.getByTestId("crm-board").getByRole("button", { name: /Riley Brooks/ }).click()
  await expect(details(page)).toContainText("CEO")
})

test("organizations: shared directory with its people and timeline", async ({ page }) => {
  await page.goto("/#/partners")
  await page.getByRole("button", { name: "Organizations", exact: true }).click()
  const table = page.getByTestId("orgs")
  await expect(table).toContainText("Desert Table Catering")
  await table.getByRole("button", { name: /Desert Table Catering/ }).click()
  const panel = details(page)
  await expect(panel).toContainText("Jamie Ortiz")
  await expect(panel.getByRole("list", { name: "Timeline" })).toContainText("Asked for a quote")
  await panel.getByRole("button", { name: /Jamie Ortiz/ }).click()
  await expect(details(page).getByRole("heading", { name: /Jamie Ortiz/ })).toBeVisible()
  await closeRail(page)
  await page.getByRole("button", { name: "+ Add organization" }).click()
  await page.getByLabel("Organization name").fill("Tempe Print Hub (fictional)")
  await page.getByRole("button", { name: "Add", exact: true }).click()
  await expect(table).toContainText("Tempe Print Hub (fictional)")
})

test("leads-only contacts stay hidden from other officers", async ({ page }) => {
  await page.goto("/#/partners")
  await expect(page.getByTestId("contacts")).toContainText("Morgan Hale")
  await closeRail(page)
  await viewAs(page, "maya")
  await expect(page.getByTestId("contacts")).not.toContainText("Morgan Hale")
  await expect(page.getByTestId("contacts")).toContainText("Jamie Ortiz")
  await page.getByLabel("Search partners").fill("morgan")
  await expect(page.getByText("No contacts match.")).toBeVisible()
})
