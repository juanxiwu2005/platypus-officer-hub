import type { DemoState, OfficerGrant } from "../data/types"
import { addDays } from "./dates"

const payload = (g: Omit<OfficerGrant, "signature"> | OfficerGrant) => JSON.stringify([g.id, g.nodeId, g.ownerId, g.ownerVersion, g.issuedOn, g.expiresOn])
const hex = (b: ArrayBuffer) => Array.from(new Uint8Array(b), x => x.toString(16).padStart(2, "0")).join("")
async function sign(key: string, value: string): Promise<string> {
  const secret = await crypto.subtle.importKey("raw", new TextEncoder().encode(key), { name: "HMAC", hash: "SHA-256" }, false, ["sign"])
  return hex(await crypto.subtle.sign("HMAC", secret, new TextEncoder().encode(value)))
}
/** Local-only demo capability; signing keys and grants are regenerated by Reset demo. */
export async function makeOfficerGrant(s: DemoState, nodeId: string): Promise<OfficerGrant> {
  const n = s.nodes.find(n => n.id === nodeId)
  if (!n?.ownerId || n.status === "done") throw new Error("Choose an open task with an owner.")
  const grant = { id: crypto.randomUUID(), nodeId, ownerId: n.ownerId, ownerVersion: n.ownerVersion ?? 0, issuedOn: s.today, expiresOn: addDays(s.today, 3), usedOn: null }
  return { ...grant, signature: await sign(s.demoLinkKey, payload(grant)) }
}
export const grantToken = (g: OfficerGrant) => `${g.id}.${g.signature}`
export const officerUrl = (origin: string, g: OfficerGrant, action?: string) => `${origin}/#/officer?token=${encodeURIComponent(grantToken(g))}${action ? `&reply=${encodeURIComponent(action)}` : ""}`
export function usableGrant(s: DemoState, token: string): OfficerGrant | undefined {
  const grant = s.officerGrants.find(g => grantToken(g) === token)
  if (!grant || grant.usedOn || s.today > grant.expiresOn) return
  const n = s.nodes.find(n => n.id === grant.nodeId)
  return n && n.status !== "done" && n.ownerId === grant.ownerId && (n.ownerVersion ?? 0) === grant.ownerVersion ? grant : undefined
}
export async function verifyOfficerGrant(s: DemoState, token: string): Promise<boolean> {
  const g = usableGrant(s, token)
  if (!g) return false
  return await sign(s.demoLinkKey, payload(g)) === g.signature
}
