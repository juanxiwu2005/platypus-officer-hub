import { expect, test } from "@playwright/test"

test.beforeEach(async ({ page }) => {
  await page.route("**/api/health", r => r.fulfill({ json: { ok: true, configured: false, provider: null, model: null } }))
})

test("reviews an event, edits it, applies once, persists and resets", async ({ page }) => {
  await page.route("**/api/command", r => r.fulfill({ json: { source: "ai", model: "test", ops: [{ op: "create_event", name: "Founder Dinner", date: "2099-01-01", type: "social", headcount: 30, venue: "campus", food: "offsite", funding: "usg", speaker: false }] } }))
  await page.goto("/#/")
  await page.locator("#command").fill("Plan Founder Dinner on Nov 19, 30 people, outside caterer, USG funding")
  await page.getByRole("button", { name: "Review changes", exact: true }).click()
  const card = page.getByTestId("change-item")
  await expect(card.getByLabel("Event date", { exact: true })).toHaveValue("2026-11-19")
  await expect(page.getByTestId("event-strip")).toHaveCount(2)
  await card.getByLabel("Event name").fill("Founder Dinner Preview")
  await card.getByLabel("Event date", { exact: true }).fill("2027-02-18")
  await card.getByRole("button", { name: "Apply this change" }).click()
  await expect(page.getByTestId("event-strip")).toHaveCount(3)
  await expect(page.getByTestId("event-strip").last()).toContainText("Founder Dinner Preview")
  await expect(card).toContainText("Approved")
  await page.reload()
  await expect(page.getByTestId("event-strip")).toHaveCount(3)
  await page.getByTestId("reset-demo").click()
  await expect(page.getByTestId("event-strip")).toHaveCount(2)
  await expect(page.getByTestId("change-set")).toHaveCount(0)
})

test("uses a clearly labelled fallback with AI off, edits owner and rejects a change", async ({ page }) => {
  await page.goto("/#/")
  await page.getByRole("checkbox", { name: "AI features" }).uncheck()
  await page.locator("#command").fill("Assign Send the October newsletter to Priya")
  await page.getByRole("button", { name: "Review changes", exact: true }).click()
  const card = page.getByTestId("change-item")
  await expect(page.getByTestId("change-set")).toContainText("AI off")
  await card.getByLabel("Owner", { exact: true }).selectOption("jordan")
  await card.getByRole("button", { name: "Apply this change" }).click()
  await expect(page.getByTestId("risk-list")).toContainText("Jordan Patel")
  await page.locator("#command").fill("Set Send the October newsletter to heavy")
  await page.getByRole("button", { name: "Review changes", exact: true }).click()
  await page.getByTestId("change-item").first().getByRole("button", { name: "Reject", exact: true }).click()
  await expect(page.getByTestId("change-item").first()).toContainText("Rejected")
})

test("risk queue has reasons and <=3 items; reminder prefers owner's channel and has four reply links", async ({ page }) => {
  await page.route("**/api/nudge/draft", r => r.fulfill({ json: { whyItMatters: "We build a stronger club together.", source: "ai" } }))
  await page.goto("/#/")
  const risk = page.getByTestId("risk-list")
  expect(await risk.locator(":scope > li").count()).toBeLessThanOrEqual(3)
  await expect(risk.locator(".late-text, .warn-text").first()).toBeVisible()
  await risk.getByRole("button", { name: "Draft reminder" }).first().click()
  const panel = page.getByTestId("nudge-panel")
  await expect(panel.getByTestId("nudge-body")).toContainText("Why now:")
  await expect(panel.getByTestId("nudge-body")).toContainText("Why it matters:")
  const selected = await panel.getByLabel("Preferred channel").inputValue()
  expect(["whatsapp", "sms", "email"]).toContain(selected)
  for (const label of ["Done", "Waiting on…", "Need help", "Need more time"]) await expect(panel.getByRole("link", { name: label, exact: true })).toHaveAttribute("href", /reply=/)
  await panel.getByLabel("Preferred channel").selectOption("email")
  const draft = panel.getByRole("link", { name: "Open Gmail draft" })
  await expect(draft).toHaveAttribute("href", /^https:\/\/mail.google.com\/mail\/\?view=cm/)
  expect(decodeURIComponent((await draft.getAttribute("href"))!)).toContain("Why now:")
  await expect(panel.getByRole("button", { name: "I sent this reminder" })).toHaveCount(0)
  await panel.getByRole("link", { name: "Need help", exact: true }).click()
  await expect(page.getByRole("region", { name: "Linked task" })).toBeVisible()
  await expect(page.getByRole("status")).toContainText("has not changed")
})

