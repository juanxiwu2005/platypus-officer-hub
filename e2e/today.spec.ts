test("server errors recover locally and invalid output cannot change anything", async ({ page }) => {
  await page.route("**/api/command", r => r.fulfill({ status: 503, json: { message: "Unavailable" } }))
  await page.goto("/#/")
  await page.locator("#command").fill("Assign Send the October newsletter to Priya")
  await page.getByRole("button", { name: "Review changes", exact: true }).click()
  await expect(page.getByTestId("change-set")).toContainText("server unavailable")
  await page.route("**/api/command", r => r.fulfill({ json: { source: "ai", ops: [{ op: "delete_node", nodeId: "t-news" }] } }))
  await page.locator("#command").fill("Delete everything")
  await page.getByRole("button", { name: "Review changes", exact: true }).click()
  await expect(page.getByRole("status")).toContainText("couldn't safely match")
  await expect(page.getByTestId("change-set")).toHaveCount(1)
})
