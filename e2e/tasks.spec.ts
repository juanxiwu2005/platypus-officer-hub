test("claims an unassigned handover, then updates waiting, help and done without duplicates", async ({ page }) => {
  const id = await createUnclaimedTask(page, "Prepare the volunteer briefing")
  await viewAs(page, "jordan")
  await page.goto(`/#/tasks?node=${encodeURIComponent(id)}`)
  const detail = page.getByTestId("task-detail")
  await detail.getByRole("button", { name: "I've got it", exact: true }).click()
  // The universal Task Details (docs/feedback-fix/TASK_DETAILS_UNIVERSAL_HANDOFF.md): one Task status menu, and Done comes from submitting the result.
  const status = detail.getByRole("combobox", { name: "Task status", exact: true })
  await expect(status).toHaveValue("accepted")
  expect(await savedTask(page, id)).toMatchObject({ status: "accepted", ownerId: "jordan" })
  await status.selectOption("waiting")
  await detail.getByRole("combobox", { name: "Waiting on", exact: true }).selectOption({ label: "Sam Okafor" })
  await detail.getByRole("textbox", { name: "What help or input is needed?" }).fill("Please confirm the volunteer briefing room")
  await detail.getByRole("button", { name: "Save waiting status" }).click()
  await expect(detail).toContainText("Waiting for: Please confirm the volunteer briefing room")
  expect(await savedTask(page, id)).toMatchObject({ status: "waiting", waitingOnPersonId: "sam" })
  await status.selectOption("blocked")
  await expect(status).toHaveValue("blocked")
  expect(await savedTask(page, id)).toMatchObject({ status: "blocked" })
  await detail.getByRole("textbox", { name: "Details", exact: true }).fill("Sam confirmed the volunteer briefing room.")
  await detail.getByRole("button", { name: "Submit & mark done", exact: true }).click()
  await expect(status).toHaveValue("done")
  await expect(detail.getByRole("button", { name: "Submit & mark done", exact: true })).toHaveCount(0)
  expect(await savedTask(page, id)).toMatchObject({ status: "done", ownerId: "jordan" })
  await page.reload()
  await expect(page.getByTestId("task-detail").getByRole("combobox", { name: "Task status", exact: true })).toHaveValue("done")
  const result = await page.evaluate(nodeId => { const s = JSON.parse(localStorage.getItem("platypus.v1.demo")!); return s.contributions.filter((c: { nodeId: string }) => c.nodeId === nodeId).length }, id)
  expect(result).toBe(1)
})

test("a financial task owner updates the club target directly while school dates and progress stay unchanged", async ({ page }) => {
  await page.goto("/#/tasks?node=e-night:purchaseRequest")
  // Let the linked task open first: on a phone its side panel covers the top bar, and viewAs must know whether it is there.
  await expect(page.getByTestId("task-detail")).toBeVisible()
  await viewAs(page, "maya")
  const before = await savedTask(page, "e-night:purchaseRequest")
  expect(before.officialDeadline).not.toBeNull()
  const requestedDate = "2027-04-01", detail = page.getByTestId("task-detail")
  await detail.getByRole("combobox", { name: "Task status", exact: true }).selectOption("extension")
  await detail.getByLabel("New target date", { exact: true }).fill(requestedDate)
  await detail.getByLabel("Message (optional)", { exact: true }).fill("We need the final vendor quote before sending the purchase request.")
  await detail.getByRole("button", { name: "Update date & notify", exact: true }).click()
  await expect(detail).toContainText("Target date updated")
  expect(await savedTask(page, before.id)).toMatchObject({ clubDeadline: requestedDate, officialDeadline: before.officialDeadline, status: before.status })
  await page.reload()
  await expect(page.getByTestId("task-detail").getByTestId("task-due")).toContainText("Apr 1")
  expect(await savedTask(page, before.id)).toMatchObject({ clubDeadline: requestedDate, officialDeadline: before.officialDeadline })
  await closeRail(page); await viewAs(page, "alex")
  await page.getByTestId("bell").click()
  await expect(page.getByTestId("private-inbox")).toContainText("Maya Chen updated")
  await expect(page.getByRole("button", { name: "Approve extension", exact: true })).toHaveCount(0)
})

test("finance completion stays in Event Budget instead of reporting an unsaved Done update", async ({ page }) => {
  await page.goto("/#/tasks?node=e-night:purchaseRequest")
  await expect(page.getByTestId("task-detail")).toBeVisible()
  await viewAs(page, "maya")
  const before = await savedTask(page, "e-night:purchaseRequest")
  const detail = page.getByTestId("task-detail")
  // A finance step only accepts its evidence (Submit result); Done is never offered here.
  await expect(detail.getByRole("button", { name: "Submit result", exact: true })).toBeEnabled()
  await expect(detail.getByRole("button", { name: /mark done/i })).toHaveCount(0)
  await expect(detail.getByRole("combobox", { name: "Task status", exact: true }).locator("option[value=done]")).toHaveCount(0)
  await expect(detail).toContainText("Completion is managed in Event Budget.")
  // The only status line is the draft autosave note: nothing reports a Done update.
  await expect(detail.getByRole("status")).toHaveText(["Changes save automatically."])
  expect(await savedTask(page, before.id)).toEqual(before)
  await detail.getByRole("link", { name: "Event Budget", exact: true }).click()
  await expect(page).toHaveURL(/events\?event=e-night&view=budget/)
  await page.reload()
  expect(await savedTask(page, before.id)).toEqual(before)
})

// S2: the demo always has a reminder plan now, so the two legacy reminder days (3 and 5) no longer become stages; the rule engine's
// reminders replace them. The three leadership stages remain. Under the plan an owner change ends the private follow-up case
// (afterReminderAction), so after the takeover is approved the case shows as stopped and offers no further approval.
test("a ten-day jump creates the three leadership stages and a recovery task, with human approval for takeover", async ({ page }) => {
  await page.goto("/#/tasks")
  await expect(page.getByRole("heading", { name: "Tasks", exact: true })).toBeVisible()
  const initialToday = await page.evaluate(() => JSON.parse(localStorage.getItem("platypus.v1.demo")!).today as string)
  const expectedDay = new Date(`${initialToday}T12:00:00Z`)
  expectedDay.setUTCDate(expectedDay.getUTCDate() + 10)
  const expectedLabel = expectedDay.toLocaleDateString("en-US", { month: "short", day: "numeric", timeZone: "UTC" })
  await demoClock(page, 10)
  await expect(page.getByTestId("demo-date")).toContainText(expectedLabel)
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem("platypus.v1.demo")!).today)).toBe(expectedDay.toISOString().slice(0, 10))
  const log = page.getByTestId("protocol-log")
  await expect(log.locator("li")).toHaveCount(3)
  for (const day of [7, 8, 10]) await expect(log.getByText(new RegExp(`^Day ${day} ·`))).toBeVisible()
  for (const day of [3, 5]) await expect(log.getByText(new RegExp(`^Day ${day} ·`))).toHaveCount(0)
  await expect(log).toContainText("24 hours")
  await expect(log).toContainText("Jordan Patel")
  await expect(log.getByRole("button", { name: "Approve recovery timeline", exact: true })).toBeVisible()
  await expect(log).not.toContainText("stopped")
  await log.getByRole("button", { name: "Approve suggested owner", exact: true }).click()
  await expect.poll(async () => page.evaluate(() => JSON.parse(localStorage.getItem("platypus.v1.demo")!).nodes.find((n: { id: string }) => n.id === "t-silence").ownerId)).toBe("alex")
  await expect(log).toContainText("stopped")
  await expect(log.getByRole("button")).toHaveCount(0)
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem("platypus.v1.demo")!).nodes.some((n: { id: string }) => n.id.startsWith("retro:")))).toBe(true)
  await viewAs(page, "maya")
  await expect(page.getByTestId("president-review")).toHaveCount(0)
  await expect(page.getByText("Demo clock", { exact: true })).toHaveCount(0)
  await page.getByRole("button", { name: /^Private updates/ }).click()
  await expect(page.getByRole("region", { name: "Private inbox" })).not.toContainText("Confirm the workshop checklist")
})

test("the task entry opens only its task, does not update on load, and supports repeat updates", async ({ page }) => {
  await enableUpdatedReminders(page)
  await page.goto("/#/tasks")
  await ask(page, "Remind Jordan about the workshop checklist")
  await page.getByRole("button", { name: "Open the draft" }).last().click()
  const panel = page.getByTestId("nudge-panel")
  const link = panel.getByRole("link", { name: "Open task", exact: true })
  // The email entry opens the task in Plan beside the club's work (docs/feedback-fix/REMINDER_PLAN_ENTRY_HANDOFF.md); this club task has no event.
  await expect(link).toHaveAttribute("href", /#\/events\?node=t-silence&access=/)
  const href = (await link.getAttribute("href"))!
  const before = await savedTask(page, "t-silence")
  await page.goto(href)
  const task = page.getByTestId("task-detail")
  await expect(task.getByRole("heading", { name: before.title, exact: true })).toBeVisible()
  await expect(page.getByRole("navigation", { name: "Event task navigation" }).getByLabel("View task", { exact: true })).toHaveValue("t-silence")
  expect((await savedTask(page, "t-silence")).status).toBe(before.status)
  const status = task.getByRole("combobox", { name: "Task status", exact: true })
  await status.selectOption("blocked")
  await expect(status).toHaveValue("blocked")
  expect((await savedTask(page, "t-silence")).status).toBe("blocked")
  await page.reload()
  await expect(status).toHaveValue("blocked")
  await status.selectOption("in_progress")
  await expect(status).toHaveValue("in_progress")
  expect((await savedTask(page, "t-silence")).status).toBe("in_progress")
})

test("tampered and reset task entries cannot update any task", async ({ page, isMobile }) => {
  await enableUpdatedReminders(page)
  // Concept F / S2: the first person's email, opened in place; each task line ends in its own "Open task" entry.
  await page.getByTestId("rq-person").first().getByTestId("rq-person-toggle").click()
  const link = page.getByTestId("rq-person").first().getByTestId("digest-body").getByRole("link", { name: "Open task", exact: true }).first()
  await expect(link).toHaveAttribute("href", /access=/)
  const href = (await link.getAttribute("href"))!
  await page.goto(`${href}0`)
  await expect(page.getByRole("heading", { name: "Check your task link" })).toBeVisible()
  await expect(page.getByTestId("task-detail")).toHaveCount(0)
  await page.goto("/#/")
  await expect(page.getByTestId("reminder-centre")).toBeVisible()
  // The Plan link opened the side panel; on a phone leaving Plan closes it again (e2e/reminder-plan-entry.spec.ts).
  if (isMobile) await expect(page.getByTestId("rail")).toBeHidden()
  await resetDemo(page)
  await page.goto(href)
  await expect(page.getByRole("heading", { name: "Check your task link" })).toBeVisible()
  await expect(page.getByTestId("task-detail")).toHaveCount(0)
})

