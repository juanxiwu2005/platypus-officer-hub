test("claims an unassigned handover, then updates waiting, help and done without duplicates", async ({ page }) => {
  await page.goto("/#/tasks?node=e-night:rsvp")
  await page.getByTestId("view-as").selectOption("jordan")
  const detail = page.getByTestId("task-detail")
  await detail.getByRole("button", { name: "I've got it", exact: true }).click()
  await expect(detail).toContainText("To do")
  await detail.getByRole("button", { name: "Waiting on…", exact: true }).click()
  await detail.getByLabel("Waiting on", { exact: true }).selectOption({ label: "Sam Okafor" })
  await detail.getByRole("button", { name: "Save waiting status" }).click()
  await expect(detail).toContainText("Waiting on: Sam Okafor")
  await detail.getByRole("button", { name: "Need help", exact: true }).click()
  await expect(detail).toContainText("Stuck")
  await detail.getByRole("button", { name: "Done", exact: true }).click()
  await expect(detail).toContainText("Completed on")
  await expect(detail.getByRole("button", { name: "Done", exact: true })).toHaveCount(0)
  await page.reload()
  await expect(page.getByTestId("task-detail")).toContainText("Completed on")
  const result = await page.evaluate(() => { const s = JSON.parse(localStorage.getItem("platypus.v1.demo")!); return s.contributions.filter((c: { nodeId: string }) => c.nodeId === "e-night:rsvp").length })
  expect(result).toBe(1)
})

test("extension needs a draft and stays pending until the president approves", async ({ page }) => {
  await page.goto("/#/tasks?node=e-night:usg")
  await page.getByTestId("view-as").selectOption("maya")
  const detail = page.getByTestId("task-detail")
  await detail.getByRole("button", { name: "Need more time", exact: true }).click()
  await detail.getByLabel("Requested club deadline", { exact: true }).fill("2026-11-06")
  await detail.getByRole("button", { name: "Request extension", exact: true }).click()
  await expect(detail.getByRole("status")).toContainText("current draft")
  await detail.getByLabel("Current draft link", { exact: true }).fill("https://example.org/current-draft")
  await detail.getByRole("button", { name: "Request extension", exact: true }).click()
  await expect(detail).toContainText("Extension awaiting review")
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem("platypus.v1.demo")!).nodes.find((n: { id: string }) => n.id === "e-night:usg").clubDeadline)).toBe("2026-10-30")
  await expect(page.getByTestId("president-review")).toHaveCount(0)
  await page.getByTestId("view-as").selectOption("alex")
  await closeRail(page)
  await page.getByRole("button", { name: "Approve extension", exact: true }).click()
  const dates = await page.evaluate(() => { const n = JSON.parse(localStorage.getItem("platypus.v1.demo")!).nodes.find((n: { id: string }) => n.id === "e-night:usg"); return [n.clubDeadline, n.officialDeadline] })
  expect(dates).toEqual(["2026-11-06", "2026-11-04"])
  await page.getByTestId("view-as").selectOption("maya")
  await expect(page.getByTestId("private-inbox")).toContainText("was approved")
})

test("a ten-day jump creates the five private stages and a recovery task, with human approval for takeover", async ({ page }) => {
  await page.goto("/#/tasks")
  await demoClock(page, 10)
  await expect(page.getByTestId("demo-date")).toContainText("Nov 1")
  const log = page.getByTestId("protocol-log")
  await expect(log.locator("li")).toHaveCount(5)
  for (const day of [3, 5, 7, 8, 10]) await expect(log.getByText(new RegExp(`^Day ${day} ·`))).toBeVisible()
  await expect(log).toContainText("24 hours")
  await expect(log).toContainText("Jordan Patel")
  await log.getByRole("button", { name: "Approve suggested owner", exact: true }).click()
  await expect(log.getByRole("button", { name: "Temporary owner assigned" })).toBeDisabled()
  await log.getByRole("button", { name: "Approve recovery timeline", exact: true }).click()
  await expect(log.getByRole("button", { name: "Recovery plan applied" })).toBeDisabled()
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem("platypus.v1.demo")!).nodes.some((n: { id: string }) => n.id.startsWith("retro:")))).toBe(true)
  await page.getByTestId("view-as").selectOption("maya")
  await expect(page.getByTestId("president-review")).toHaveCount(0)
  await expect(page.getByText("Demo clock", { exact: true })).toHaveCount(0)
  await expect(page.getByTestId("private-inbox")).not.toContainText("Confirm the workshop checklist")
})

test("the officer link opens only its task, does not change it on load, and can be used once", async ({ page }) => {
  await page.goto("/#/tasks")
  await ask(page, "Remind Jordan about the workshop checklist")
  await page.getByRole("button", { name: "Open the draft" }).last().click()
  const panel = page.getByTestId("nudge-panel")
  const link = panel.getByRole("link", { name: "Need help", exact: true })
  await expect(link).toHaveAttribute("href", /#\/officer\?token=/)
  const href = (await link.getAttribute("href"))!
  const before = await page.evaluate(() => JSON.parse(localStorage.getItem("platypus.v1.demo")!).nodes.find((n: { id: string }) => n.id === "t-silence").status)
  await link.click()
  await expect(page.getByRole("heading", { name: "Hi Jordan" })).toBeVisible()
  await expect(page.getByRole("navigation", { name: "Sections" })).toHaveCount(0)
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem("platypus.v1.demo")!).nodes.find((n: { id: string }) => n.id === "t-silence").status)).toBe(before)
  await page.getByRole("button", { name: "Need help", exact: true }).click()
  await expect(page.getByRole("heading", { name: "Update saved" })).toBeVisible()
  await page.goto("/" + href)
  await expect(page.getByRole("heading", { name: "Update saved" })).toBeVisible()
  await expect(page.getByRole("button", { name: "Need help", exact: true })).toHaveCount(0)
})

