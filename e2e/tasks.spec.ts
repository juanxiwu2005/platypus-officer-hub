test("claims an unassigned handover, then updates waiting, help and done without duplicates", async ({ page }) => {
  const id = await createUnclaimedTask(page, "Prepare the volunteer briefing")
  await viewAs(page, "jordan")
  await page.goto(`/#/tasks?node=${encodeURIComponent(id)}`)
  const detail = page.getByTestId("task-detail")
  await detail.getByRole("button", { name: "I've got it", exact: true }).click()
  await expect(detail).toContainText("To do")
  expect(await savedTask(page, id)).toMatchObject({ status: "accepted", ownerId: "jordan" })
  await detail.getByRole("button", { name: "Waiting on…", exact: true }).click()
  await detail.getByLabel("Waiting on", { exact: true }).selectOption({ label: "Sam Okafor" })
  await detail.getByRole("button", { name: "Save waiting status" }).click()
  await expect(detail).toContainText("Waiting on: Sam Okafor")
  expect(await savedTask(page, id)).toMatchObject({ status: "waiting", waitingOnPersonId: "sam" })
  await detail.getByRole("button", { name: "Need help", exact: true }).click()
  await expect(detail).toContainText("Stuck")
  expect(await savedTask(page, id)).toMatchObject({ status: "blocked" })
  await detail.getByRole("button", { name: "Mark done", exact: true }).click()
  await expect(detail).toContainText("Completed on")
  await expect(detail.getByRole("button", { name: "Mark done", exact: true })).toHaveCount(0)
  await page.reload()
  await expect(page.getByTestId("task-detail")).toContainText("Completed on")
  const result = await page.evaluate(nodeId => { const s = JSON.parse(localStorage.getItem("platypus.v1.demo")!); return s.contributions.filter((c: { nodeId: string }) => c.nodeId === nodeId).length }, id)
  expect(result).toBe(1)
})

test("extension needs a draft and stays pending until the president approves", async ({ page }) => {
  await page.goto("/#/tasks?node=e-night:purchaseRequest")
  await viewAs(page, "maya")
  const before = await savedTask(page, "e-night:purchaseRequest")
  expect(before.officialDeadline).not.toBeNull()
  const requestedDate = "2027-04-01"
  const detail = page.getByTestId("task-detail")
  await detail.getByRole("button", { name: "Need more time", exact: true }).click()
  await detail.getByLabel("Requested club deadline", { exact: true }).fill(requestedDate)
  await detail.getByRole("button", { name: "Request extension", exact: true }).click()
  await expect(detail.getByRole("status")).toContainText("current draft")
  await detail.getByLabel("Current draft link", { exact: true }).fill("https://example.org/current-draft")
  await detail.getByRole("button", { name: "Request extension", exact: true }).click()
  await expect(detail).toContainText("Extension awaiting review")
  expect(await savedTask(page, before.id)).toMatchObject({ clubDeadline: before.clubDeadline, officialDeadline: before.officialDeadline })
  await page.reload()
  await expect(page.getByTestId("task-detail")).toContainText("Extension awaiting review")
  await expect(page.getByTestId("president-review")).toHaveCount(0)
  await viewAs(page, "alex")
  await closeRail(page)
  await page.getByRole("button", { name: "Approve extension", exact: true }).click()
  const dates = await page.evaluate(() => { const n = JSON.parse(localStorage.getItem("platypus.v1.demo")!).nodes.find((n: { id: string }) => n.id === "e-night:purchaseRequest"); return [n.clubDeadline, n.officialDeadline] })
  expect(dates).toEqual([requestedDate, before.officialDeadline])
  await page.reload()
  expect(await savedTask(page, before.id)).toMatchObject({ clubDeadline: requestedDate, officialDeadline: before.officialDeadline })
  await viewAs(page, "maya")
  await closeRail(page)
  await page.getByRole("button", { name: /^Private updates/ }).click()
  await expect(page.getByRole("region", { name: "Private inbox" })).toContainText("was approved")
})

