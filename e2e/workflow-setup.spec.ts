import { expect, test, type Page } from "@playwright/test"
import { closeRail, noOverflow } from "./helpers"

// Onboarding uses the standard workflow. Club-specific edits are manual and reviewed
// before approval; the removed planning-material AI step must never be requested.
const openStep = async (page: Page, key: string) => {
  await closeRail(page)
  await page.getByTestId(`flow-node-${key}`).click()
  if (test.info().project.name === "mobile") await page.getByTestId("flow-menu").getByRole("button", { name: "Open details" }).click()
  return page.getByTestId("workflow-step-panel")
}
const workflowStep = async (page: Page) => {
  await page.goto("/#/setup")
  const step = page.getByTestId("setup-step")
  for (let i = 0; i < 4; i++) await step.getByRole("button", { name: "Continue", exact: true }).click()
  return step
}

test.beforeEach(async ({ page }) => {
  await page.route("**/api/health", r => r.fulfill({ json: { ok: true, configured: true, provider: "mock", model: "mock" } }))
  await page.route("**/api/command", r => r.fulfill({ status: 503, json: { message: "Local demo" } }))
})

test("onboarding starts with the standard workflow without planning notes, fictional files, or an AI workflow request", async ({ page }) => {
  let workflowCalls = 0
  await page.route("**/api/setup/workflow", r => { workflowCalls++; return r.fulfill({ status: 500, json: { message: "Should not be called" } }) })
  await page.goto("/#/setup")
  const step = page.getByTestId("setup-step")
  for (let i = 0; i < 3; i++) await step.getByRole("button", { name: "Continue", exact: true }).click()
  await expect(step.getByLabel("Planning notes (how your club runs events)")).toHaveCount(0)
  await expect(step.getByLabel("Fictional planning files", { exact: true })).toHaveCount(0)
  await step.getByRole("button", { name: "Continue", exact: true }).click()
  await expect(step.getByRole("heading", { level: 2 })).toHaveText("Step 5 of 6 · Event workflow")
  await expect(step.getByRole("status").first()).toContainText("This is the standard workflow")
  await expect(step.getByTestId("flow-chart")).toBeVisible()
  expect(workflowCalls).toBe(0)
})

test("manual workflow edits keep ASU dependencies, support Undo, and persist into the approved first event and Settings", async ({ page }) => {
  const step = await workflowStep(page)
  const before = await page.evaluate(() => localStorage.getItem("platypus.v1.demo"))
  let panel = await openStep(page, "budget")
  await panel.getByLabel("Step name", { exact: true }).fill("Club budget")
  await panel.getByLabel("Days of work").fill("4")
  await panel.getByLabel("Done by").selectOption("r-fin")
  await closeRail(page)
  const budget = step.getByTestId("flow-node-budget")
  if (test.info().project.name === "mobile") await budget.click(); else await budget.dblclick()
  await page.getByTestId("flow-menu").getByRole("button", { name: "Add a step after this one" }).click()
  panel = page.getByTestId("workflow-step-panel")
  await panel.getByLabel("Step name", { exact: true }).fill("Photo release check")
  await expect(panel.getByLabel("Done by")).toHaveValue("r-fin")
  await closeRail(page)
  await expect(step.getByTestId("flow-node-new-step")).toHaveAttribute("aria-label", /Photo release check/)
  await step.getByTestId("flow-undo").click()
  await expect(step.getByTestId("flow-node-new-step")).toHaveCount(0)

  panel = await openStep(page, "purchaseRequest")
  await expect(panel).toContainText("ASU rule R09")
  await expect(panel.getByRole("button", { name: "Delete this step" })).toHaveCount(0)
  await panel.getByRole("button", { name: /no longer waits for Budget Approval/ }).click()
  await closeRail(page)
  await expect(step.getByTestId("wf-blocked")).toContainText("must wait for")
  await expect(step.getByTestId("flow-node-purchaseRequest")).toHaveClass(/mark-error/)
  await step.getByRole("button", { name: "Continue", exact: true }).click()
  await expect(step.getByRole("alert")).toContainText("must wait for")
  await expect(step.getByRole("heading", { level: 2 })).toHaveText("Step 5 of 6 · Event workflow")
  panel = await openStep(page, "purchaseRequest")
  await panel.getByLabel("Add a step that Purchase Request waits for").selectOption({ label: "Budget Approval" })
  await closeRail(page)
  await expect(step.getByTestId("wf-blocked")).toHaveCount(0)
  await step.getByRole("button", { name: "Back", exact: true }).click()
  await step.getByRole("button", { name: "Continue", exact: true }).click()
  await expect(step.getByTestId("flow-node-budget")).toHaveAttribute("aria-label", /^Club budget\./)
  expect(await page.evaluate(() => localStorage.getItem("platypus.v1.demo"))).toBe(before)
  await step.getByRole("button", { name: "Continue", exact: true }).click()
  await step.getByRole("button", { name: "Prepare first workflow", exact: true }).click()
  await expect(page.getByTestId("setup-preview")).toBeVisible()
  await step.getByRole("checkbox", { name: "I reviewed this event and want to start this demo workspace." }).check()
  await step.getByRole("button", { name: "Approve & start workspace", exact: true }).click()
  await expect(page.getByRole("heading", { level: 1 })).toHaveText("Events")
  const saved = await page.evaluate(() => {
    const s = JSON.parse(localStorage.getItem("platypus.v1.demo")!)
    return { budget: s.org.eventWorkflow.steps.find((x: { key: string }) => x.key === "budget"), node: s.nodes.find((n: { stepKey: string }) => n.stepKey === "budget"), purchase: s.org.eventWorkflow.steps.find((x: { key: string }) => x.key === "purchaseRequest") }
  })
  expect(saved.budget).toMatchObject({ title: "Club budget", estDays: 4, ownerRoleId: "r-fin" })
  expect(saved.node).toMatchObject({ title: "Club budget", ownerId: "maya" })
  expect(saved.purchase.dependsOn).toContain("budgetApproval")
  await page.goto("/#/settings")
  await page.getByRole("button", { name: "Workflow", exact: true }).click()
  const settings = page.getByTestId("workflow-settings")
  panel = await openStep(page, "budget")
  await expect(panel.getByLabel("Step name", { exact: true })).toHaveValue("Club budget")
  await panel.getByLabel("Days of work").fill("3")
  await closeRail(page)
  await expect(settings.getByRole("status").last()).toContainText("Saved")
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem("platypus.v1.demo")!).org.eventWorkflow.steps.find((x: { key: string }) => x.key === "budget").estDays)).toBe(3)
  await settings.getByRole("button", { name: "Go back to the standard workflow" }).click()
  await expect(settings.getByTestId("flow-node-budget")).toHaveAttribute("aria-label", /^Budget\./)
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem("platypus.v1.demo")!).org.eventWorkflow)).toBeUndefined()
  expect(await noOverflow(page)).toBeLessThanOrEqual(1)
})

test("AI failure still allows standard owners, manual first-event review and approval", async ({ page }) => {
  const step = await workflowStep(page)
  await expect(step.getByRole("status").first()).toContainText("This is the standard workflow")
  await expect(step.getByTestId("workflow-changes")).toHaveCount(0)
  await expect(step.getByTestId("workflow-ok")).toBeVisible()
  const panel = await openStep(page, "budget")
  await expect(panel.getByLabel("Done by")).toHaveValue("r-fin")
  await closeRail(page)
  await step.getByRole("button", { name: "Continue", exact: true }).click()
  await step.getByRole("button", { name: "Prepare first workflow", exact: true }).click()
  await expect(step).toContainText("Local demo fallback")
  await step.getByLabel("Event name", { exact: true }).fill("Manually reviewed dinner")
  await step.getByRole("checkbox", { name: "I reviewed this event and want to start this demo workspace." }).check()
  await step.getByRole("button", { name: "Approve & start workspace", exact: true }).click()
  await expect(page.getByRole("heading", { level: 1 })).toHaveText("Events")
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem("platypus.v1.demo")!).events[0].name)).toBe("Manually reviewed dinner")
  expect(await noOverflow(page)).toBeLessThanOrEqual(1)
})

test("a signed-out constitution request is not retried; the unfinished setup restores and cancel removes it", async ({ page }) => {
  const bodies: Record<string, unknown>[] = []
  await page.route("**/api/setup/constitution", r => { bodies.push(r.request().postDataJSON()); return r.fulfill({ status: 401, contentType: "text/html", body: "<html><title>Login Redirect</title></html>" }) })
  await page.goto("/#/setup")
  await page.reload() // finish the existing workspace's deterministic load-time repairs before snapshotting it
  const before = await page.evaluate(() => localStorage.getItem("platypus.v1.demo"))
  const step = page.getByTestId("setup-step")
  await step.getByRole("button", { name: "Use the sample constitution" }).click()
  await step.getByRole("button", { name: "Continue", exact: true }).click()
  await expect(step.getByRole("status").first()).toContainText("your Netlify sign-in for this preview has expired")
  await expect(step.getByRole("status").first()).toContainText("setup is kept")
  expect(bodies).toHaveLength(1)
  expect(Object.keys(bodies[0]).sort()).toEqual(["part", "text"])
  expect(JSON.stringify(bodies)).not.toMatch(/personalBuffer|busyWeeks|dataUrl|careerGoal|phone|9999000|@example\.org/)
  await step.getByLabel("Club mission").fill("Fictional restored mission")
  await expect.poll(() => page.evaluate(() => new Promise(resolve => {
    const req = indexedDB.open("platypus.docs", 1)
    req.onsuccess = () => { const db = req.result; const read = db.transaction("docs").objectStore("docs").get("setup-draft"); read.onsuccess = () => { resolve(read.result?.value.draft.mission); db.close() } }
  }))).toBe("Fictional restored mission")
  await page.reload()
  const restore = page.getByTestId("setup-restore")
  await expect(restore).toContainText("You have an unfinished setup")
  await restore.getByRole("button", { name: "Restore it" }).click()
  await expect(restore).toHaveCount(0)
  await expect(step.getByRole("heading", { level: 2 })).toHaveText("Step 2 of 6 · Semester goals")
  await expect(step.getByLabel("Club mission")).toHaveValue("Fictional restored mission")
  expect(bodies).toHaveLength(1)
  expect(await page.evaluate(() => localStorage.getItem("platypus.v1.demo"))).toBe(before)
  await step.getByRole("link", { name: "Cancel setup" }).click()
  await page.goto("/#/setup")
  await page.reload()
  await expect(restore).toHaveCount(0)
})
