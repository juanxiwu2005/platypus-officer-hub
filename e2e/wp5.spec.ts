test("sourced handbook requires outgoing confirmation before presidential approval", async ({ page }) => {
  await page.route("**/api/handbook/draft", r => {
    const data = r.request().postDataJSON(); expect(JSON.stringify(data)).not.toMatch(/personalBuffer|demoLinkKey|email|dataUrl|busyWeeks/)
    return r.fulfill({ json: { entries: [{ sourceId: "task:t-recon", text: "Hallucinated 2099-01-01" }, { sourceId: "interview:r-fin:1" }], model: "mock-live-contract", provider: "mock", source: "ai" } })
  })
  await page.goto("/#/handoff")
  await expect(page.getByRole("button", { name: "Save dates" })).toBeVisible() // the sample club's handoff season is already open (P3-A)
  await page.getByRole("button", { name: /^Treasurer handbook/ }).click()
  const role = page.getByRole("region", { name: "Treasurer handbook" })
  await role.getByRole("button", { name: "Draft role handbook" }).click()
  const draft = role.getByTestId("handbook-draft")
  await expect(draft).toContainText("AI-selected source extracts")
  await expect(draft).not.toContainText("Hallucinated")
  await expect(role.getByRole("button", { name: "Approve as president", exact: true })).toBeDisabled()
  await expect(role.getByRole("button", { name: "Confirm as outgoing officer", exact: true })).toBeDisabled()
  // The handbook reads in sections (stage 4): the interview note comes first, so the task record is Source 2.
  await draft.getByText("Source 2:", { exact: false }).click()
  await expect(draft.getByRole("link", { name: "Open task record" })).toBeVisible()
  await viewAs(page, "maya")
  await role.getByRole("button", { name: "Confirm as outgoing officer", exact: true }).click()
  await viewAs(page, "alex")
  await role.getByRole("button", { name: "Approve as president", exact: true }).click()
  await expect(role).toContainText("President approved")
  await page.reload()
  await page.getByRole("button", { name: /^Treasurer handbook/ }).click()
  await expect(page.getByRole("region", { name: "Treasurer handbook" })).toContainText("President approved")
  expect(await noOverflow(page)).toBeLessThanOrEqual(1)
})
